import pandas as pd

def export_results_to_csv(results_dict, csv_path="evaluation_results.csv"):
    """
    Exports a dict of evaluation results to a CSV file.

    Args:
      results_dict: dict mapping dataset names to their result dicts, e.g.
        {
          "qg_squad": {
            "evaluated": 100,
            "avg_bertscore": 0.4321,
            "avg_moverscore": 0.3876
          },
          "qg_squadshifts": { ... }
        }
      csv_path:     path (including filename) where the CSV will be saved.
    """
    rows = []
    for ds_name, res in results_dict.items():
        rows.append({
            "dataset": ds_name,
            "passages_evaluated": res["evaluated"],
            "avg_bertscore_f1": res["avg_bertscore"],
            "avg_moverscore_f1": res["avg_moverscore"]
        })
    df = pd.DataFrame(rows)
    df.to_csv(csv_path, index=False)
    print(f"Results saved to {csv_path}")

