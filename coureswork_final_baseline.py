# Cell 2: load_and_group
def load_and_group(dataset_name, config=None, split="test"):
    """
    Loads a 🤗 dataset split and groups by passage.
    Returns: { passage_str: [ {question, answer}, … ] }
    """
    if config:
        ds = load_dataset(dataset_name, config)[split]
    else:
        ds = load_dataset(dataset_name)[split]

    context_dict = {}
    for ex in ds:
        p = ex["paragraph"]
        context_dict.setdefault(p, []).append({
            "question": ex["question"],
            "answer": ex["answer"]
        })
    return context_dict

# Cell 3: format_qa_list
def format_qa_list(qa_list):
    """
    Converts a list of {'question', 'answer'} dicts into standardized strings.
    """
    return [f"question: {qa['question']}, answer: {qa['answer']}" for qa in qa_list]

# Cell 4: generate_baseline_qa
def generate_baseline_qa(model, passage):
    """
    Uses the QG model to generate a list of {'question', 'answer'} dicts.
    If no answer is found in the passage, returns an empty list.
    """
    try:
        raw = model.generate_qa(passage)
        return [{"question": q, "answer": a} for q, a in raw]
    except AnswerNotFoundError:
        # no answer candidate found in this passage
        print(f"  [!] Skipping passage (no answer found)")
        return []

# Cell 5: score_qa_pairs
def score_qa_pairs(preds, refs, metric="bertscore"):
    """
    Computes QAAlignedF1Score (mean) for a single passage.
    preds & refs: lists of formatted strings.
    metric: "bertscore" or "moverscore"
    """
    scorer = QAAlignedF1Score(base_metric=metric)
    scores = scorer.get_score(preds, refs)
    return float(np.mean(scores))

# Cell 6: evaluate_dataset
def evaluate_dataset(model, context_dict, max_passages=100):
    """
    Runs generation+scoring on up to max_passages randomly selected passages.
    Skips passages that exceed the model's maximum input length.
    Returns: {
      'evaluated': int,
      'avg_bertscore': float,
      'avg_moverscore': float
    }
    """
    # Randomly shuffle the passages
    all_passages = list(context_dict.items())
    random.shuffle(all_passages)

    bert_scores, move_scores = [], []
    count = 0
    for passage, ref_qas in all_passages:
        if count >= max_passages:
            break

        try:
            pred_qas = generate_baseline_qa(model, passage)
            pred_fmt = format_qa_list(pred_qas)
            ref_fmt = format_qa_list(ref_qas)
            if not pred_fmt or not ref_fmt:
                continue

            bert_scores.append(score_qa_pairs(pred_fmt, ref_fmt, metric="bertscore"))
            move_scores.append(score_qa_pairs(pred_fmt, ref_fmt, metric="moverscore"))
            count += 1
        except ExceedMaxLengthError:
            print(f"  [!] Skipping passage (exceeds max length)")
            continue

    return {
        "evaluated": len(bert_scores),
        "avg_bertscore": float(np.mean(bert_scores)) if bert_scores else 0.0,
        "avg_moverscore": float(np.mean(move_scores)) if move_scores else 0.0
    }

